function getPushMessages(pushType) {
  if (pushType === PUSH_TYPES.WIN_STREAK) return WIN_STREAK_MESSAGES;
  if (pushType === PUSH_TYPES.FRIEND_DUEL) return FRIEND_DUEL_MESSAGES;
  return INACTIVE_24H_MESSAGES;
}

function pushTypeFromStartParam(value) {
  const entry = Object.entries(PUSH_START_PARAMS).find(([, startParam]) => startParam === value);
  return entry?.[0] || "";
}

